""" Existem 3 tipos de coleções no python
Lista
Tupla (Não se pode alterar as variaveis dentro)
Dicionario (Se assemelha o Json do Java Script)
"""

# lista de nomes
nomes = ["Fulano", "Cicrano", "Beltrano", "João", "Maria", "José"]

# O laço For é o proprio contador, sendo ideal para listas
for n in nomes:
    print(f"\n{n}")